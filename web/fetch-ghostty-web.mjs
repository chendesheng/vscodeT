#!/usr/bin/env node
// Fetches the pinned ghostty-web npm tarball into the build output.
//
// The browser bundle and wasm are not checked in. Pages and local demo builds run
// this step before the page is served; the lock file pins the package version,
// tarball hash and the hash of every extracted file.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const here = path.dirname(fileURLToPath(import.meta.url));
const lock = JSON.parse(fs.readFileSync(path.join(here, 'ghostty-web.lock.json'), 'utf8'));
const outDir = path.resolve(process.argv[2] ?? 'zig-out/pages/vendor/ghostty-web');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function fileMatches(file) {
  const dest = path.join(outDir, file.to);
  if (!fs.existsSync(dest)) return false;
  return sha256(fs.readFileSync(dest)) === file.sha256;
}

if (lock.files.every(fileMatches)) {
  console.log(`[ghostty-web] ${lock.version} already present in ${outDir}`);
  process.exit(0);
}

console.log(`[ghostty-web] fetching ${lock.name}@${lock.version}`);
const response = await fetch(lock.tarball, { redirect: 'follow' });
if (!response.ok) {
  throw new Error(`failed to fetch ${lock.tarball}: ${response.status} ${response.statusText}`);
}
const tarball = Buffer.from(await response.arrayBuffer());
const digest = sha256(tarball);
if (digest !== lock.tarballSha256) {
  throw new Error(`tarball hash mismatch: expected ${lock.tarballSha256}, got ${digest}`);
}

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'ghostty-web-'));
try {
  const tarballPath = path.join(temp, 'package.tgz');
  fs.writeFileSync(tarballPath, tarball);
  execFileSync('tar', ['-xzf', tarballPath, '-C', temp], { stdio: 'inherit' });
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  for (const file of lock.files) {
    const source = path.join(temp, file.from);
    const dest = path.join(outDir, file.to);
    fs.copyFileSync(source, dest);
    const actual = sha256(fs.readFileSync(dest));
    if (actual !== file.sha256) {
      throw new Error(`hash mismatch for ${file.to}: expected ${file.sha256}, got ${actual}`);
    }
  }

  const readme = [
    '# ghostty-web (fetched at build time)',
    '',
    `- Package: \`${lock.name}@${lock.version}\``,
    `- Tarball: ${lock.tarball}`,
    `- Tarball SHA-256: \`${lock.tarballSha256}\``,
    '- Upstream: https://github.com/coder/ghostty-web',
    '- License: MIT (`LICENSE`)',
    '',
    'This directory is generated by `web/fetch-ghostty-web.mjs`. Nothing in it is',
    'checked into the repository; `zig build wasm` runs the fetch step before the',
    'page is deployed or served. Do not edit these files by hand.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'README.md'), readme);
  console.log(`[ghostty-web] installed ${lock.version} into ${outDir}`);
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
