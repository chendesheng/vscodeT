#!/usr/bin/env python3
"""Regenerate (or check) the embedded cassette indexes used by replay tests."""
import argparse
from pathlib import Path

from cassette_files import CassetteFileError, load_cases, tracked_names

ROOT = Path(__file__).resolve().parents[2]
TARGETS = [
    (ROOT / "src/vs/editor/contrib/vim/test/data/oracle", ROOT / "src/vs/editor/contrib/vim/test/browser/vimCassettes.generated.zig"),
    (ROOT / "src/vs/editor/contrib/helix/test/data/oracle", ROOT / "src/vs/editor/contrib/helix/test/browser/helixCassettes.generated.zig"),
]


def render(files: list[Path]) -> str:
    lines = [
        "// Generated by scripts/oracle/generate_cassette_index.py. Do not edit.",
        "pub const files = [_]struct { name: []const u8, data: []const u8 }{",
    ]
    for path in files:
        name = path.name
        lines.append(f'    .{{ .name = "{name}", .data = @embedFile("../data/oracle/{name}") }},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if indexes are stale; do not write files")
    args = parser.parse_args()
    # Validate both corpora before writing either index.
    try:
        corpora = [(out, load_cases(data_dir, tracked_names=tracked_names(data_dir, ROOT))) for data_dir, out in TARGETS]
    except CassetteFileError as error:
        raise SystemExit(str(error)) from error
    for out, files in corpora:
        expected = render(files)
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"{out.relative_to(ROOT)}: stale index; regenerate it")
        else:
            out.write_text(expected, encoding="utf-8")
        print(f"{out.relative_to(ROOT)}: {len(files)} cassettes")


if __name__ == "__main__":
    main()
